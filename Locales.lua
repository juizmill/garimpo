local strings = { enUS = enUS, ptBR = ptBR }
local active = enUS

ns.L = setmetatable({}, {
  __index = function(_, key)
    return active[key] or enUS[key] or key
  end,
})

-- choice: "auto", "ptBR" or "enUS". Auto follows the game client.
function ns:SetLanguage(choice)
  local lang = choice
  if not lang or lang == "auto" or not strings[lang] then
    lang = GetLocale() == "ptBR" and "ptBR" or "enUS"
  end
  active = strings[lang]
  ns.lang = lang
end

ns:SetLanguage("auto")
